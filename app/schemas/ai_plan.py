from datetime import date
from typing import List, Optional
from pydantic import BaseModel, Field


class PlanActionItem(BaseModel):
    """An individual actionable gardening task recommended for today."""

    title: str = Field(..., description="Short, clear instruction (e.g. 'Do not water tomatoes today')")
    description: str = Field(..., description="Actionable rationale based on weather, plant need, or memory")
    category: str = Field(default="care", description="Category: watering, harvest, inspection, planting, soil, maintenance")
    plant_id: Optional[int] = Field(default=None, description="Target plant ID if plant-specific")
    plant_name: Optional[str] = Field(default=None, description="Name of the plant if plant-specific")
    priority: str = Field(default="medium", description="Priority level: high, medium, low")


class DailyGardenPlan(BaseModel):
    """The personalized Daily Garden Plan generated by Thinking Machines."""

    garden_id: int
    garden_name: str
    plan_date: date
    weather_summary: str
    action_items: List[PlanActionItem] = Field(default_factory=list, description="Ordered list of recommended tasks")
    reasoning_notes: str = Field(..., description="Summary of how weather, plant state, memory, and knowledge were factored in")
    outdoor_motivation: str = Field(..., description="Motivational message encouraging the gardener to go outside and touch grass")
    generated_by: str = Field("thinking_machines", description="Origin: thinking_machines or rule_engine_fallback")


class GeneratePlanRequest(BaseModel):
    """Request schema for generating a Daily Garden Plan."""

    garden_id: int = Field(..., description="Garden ID to build the daily plan for")
    target_date: Optional[date] = Field(default=None, description="Optional target date, defaults to today")
    save_tasks_to_db: bool = Field(default=True, description="Whether to automatically persist the plan actions to the garden_tasks table")

